#!/usr/bin/env python3
# bend/Prompts.bend from UniiChat's own sources, word for word:
# `tools/prompts.py UNIICHAT_DIR > bend/Prompts.bend`. Its prompt.txt (a
# turn's and a compaction's system prompt), the subagent's and the devices'
# docs (Tools.ts), the goal check's prompts (Server.ts), the agents' names
# (Names.ts). The flake's `prompts` check regenerates it and compares.
import re, sys

src = sys.argv[1]
read = lambda f: open(src + "/" + f, encoding="utf-8").read()
tools, server, names = read("Tools.ts"), read("Server.ts"), read("Names.ts")


def tpl(text, name):
    m = re.search(r"^const " + name + r" *= `(.*?)`;", text, re.S | re.M)
    if not m or "${" in m.group(1):
        sys.exit("prompts.py: no plain template " + name)
    return m.group(1).replace("\\`", "`")


def lit(text, name):
    m = re.search(r"^const " + name + r' *= "((?:[^"\\]|\\.)*)";', text, re.M)
    if not m:
        sys.exit("prompts.py: no string " + name)
    return m.group(1).encode().decode("unicode_escape")


def words(text, name):
    m = re.search(r"^const " + name + r" = `(.*?)`", text, re.S | re.M)
    return m.group(1).split()


def bend(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif ord(c) < 32 or ord(c) > 126:
            sys.exit("prompts.py: a character to escape: " + repr(c))
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def blist(xs):
    return "[" + ", ".join(bend(x) for x in xs) + "]"


defs = [
    ("pr.master", "the master's prompt, a turn's and a compaction's (prompt.txt)", read("prompt.txt").strip()),
    ("pr.sub.head", "a subagent's part of its prompt (Tools.ts SUB_HEAD)", tpl(tools, "SUB_HEAD")),
    ("pr.view.doc", "the view, for a subagent (Tools.ts VIEW_DOC)", tpl(tools, "VIEW_DOC")),
    ("pr.devices", "the devices, for a subagent (Tools.ts DEVICES)", tpl(tools, "DEVICES")),
    ("pr.devices.none", "no device open (Tools.ts DEVICES_NONE)", lit(tools, "DEVICES_NONE")),
    ("pr.head", "a turn's message's head (Server.ts HEAD)", lit(server, "HEAD")),
    ("pr.goal", "a goal check's system prompt (Server.ts GOAL)", lit(server, "GOAL")),
    ("pr.goal.ask", "before the goal, in a check's message (Server.ts GOAL_ASK)", lit(server, "GOAL_ASK")),
    ("pr.goal.no", "the nudge of a goal not met (Server.ts GOAL_NO)", lit(server, "GOAL_NO")),
]

print("""import Base

# Prompts: UniiChat's own, word for word, generated by tools/prompts.py from
# the pinned UniiChat (do not edit: the flake's `prompts` check compares).
# Every def is prefixed `pr.`.
""")
for name, doc, text in defs:
    print("# " + doc)
    print("def " + name + "() -> String:")
    print("  " + bend(text))
    print()
print("# the agents' names, a common adjective and noun (Names.ts)")
print("def pr.adjs() -> List<&2, String>:")
print("  " + blist(words(names, "ADJS")))
print()
print("def pr.nouns() -> List<&2, String>:")
print("  " + blist(words(names, "NOUNS")))
